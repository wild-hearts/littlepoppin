// publish-extras.mjs — upload the built printable ranges to Vercel Blob and register
// them as sellable products.
//
// Run AFTER scripts/build-extras.mjs. Re-runnable: an extra that already has a blob
// pathname is skipped, so re-running does not re-upload 30 MB PDFs or mint new paths.
// Force a re-upload of one item with:  node scripts/publish-extras.mjs --force <sku>
//
// Writes lib/extras-products.generated.js, which lib/products.js merges into
// DIGITAL_PRODUCTS — so checkout, delivery and the download page all work unchanged.

import { put } from '@vercel/blob';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { EXTRAS } from '../lib/extras.js';

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const GEN = path.join(REPO, 'lib', 'extras-products.generated.js');
const PDF_DIR = path.join(REPO, 'dist', 'extras');

function token() {
  if (process.env.BLOB_READ_WRITE_TOKEN) return process.env.BLOB_READ_WRITE_TOKEN;
  const p = path.join(REPO, '.env.local');
  if (fs.existsSync(p)) {
    const m = fs.readFileSync(p, 'utf8').match(/BLOB_READ_WRITE_TOKEN\s*=\s*(.+)/);
    if (m) return m[1].trim().replace(/^["']|["']$/g, '');
  }
  return null;
}

const tok = token();
if (!tok) { console.error('Set BLOB_READ_WRITE_TOKEN in .env.local (Vercel → Storage → Blob).'); process.exit(1); }

const args = process.argv.slice(2);
const force = args.includes('--force') ? args[args.indexOf('--force') + 1] : null;

// Carry forward already-published pathnames — same principle as the prints build.
const existing = await (async () => {
  try {
    const { GENERATED_EXTRAS } = await import('../lib/extras-products.generated.js');
    return Object.fromEntries(Object.entries(GENERATED_EXTRAS).filter(([, v]) => v.file).map(([k, v]) => [k, v.file]));
  } catch { return {}; }
})();

const out = {};
let uploaded = 0, skipped = 0, missing = 0;

for (const e of EXTRAS) {
  const pdf = path.join(PDF_DIR, `${e.sku}.pdf`);
  const previewRel = `/images/extras/${e.sku}.jpg`;
  const hasPreview = fs.existsSync(path.join(REPO, previewRel.replace(/^\//, '')));

  let file = existing[e.sku] || null;

  if (file && e.sku !== force) {
    skipped++;
  } else if (!fs.existsSync(pdf)) {
    console.log(`  ✗ ${e.sku} — dist/extras/${e.sku}.pdf not found (run build-extras.mjs first)`);
    missing++;
  } else {
    try {
      const blob = await put(`extras/${e.sku}.pdf`, fs.readFileSync(pdf), {
        access: 'private', token: tok, addRandomSuffix: true, contentType: 'application/pdf',
      });
      file = blob.pathname;
      uploaded++;
      process.stdout.write('.');
    } catch (err) {
      console.log(`\n  ✗ ${e.sku} — ${err.message}`);
    }
  }

  out[e.sku] = {
    sku: e.sku, name: e.name, title: e.title, description: e.description,
    price: e.price, kind: e.kind,
    preview: hasPreview ? previewRel : null,
    file,
  };
}

const body = Object.values(out).map((p) =>
  `  '${p.sku}': { sku: '${p.sku}', name: ${JSON.stringify(p.name)}, title: ${JSON.stringify(p.title)}, ` +
  `description: ${JSON.stringify(p.description)}, price: ${p.price}, kind: '${p.kind}', ` +
  `preview: ${p.preview ? `'${p.preview}'` : 'null'}, file: ${p.file ? `'${p.file}'` : 'null'} },`
).join('\n');

fs.writeFileSync(GEN,
  `// AUTO-GENERATED by scripts/publish-extras.mjs — do not edit by hand.
// Printable ranges built from the art library (colouring books, milestone cards, calendar).
// 'file' is the PRIVATE Vercel Blob pathname of the finished PDF; null blocks checkout.
// These carry NO 'section' field on purpose — lib/printclub.js only rotates over prints
// that have one, which keeps colouring books out of the monthly Print Club pick.
export const GENERATED_EXTRAS = {
${body}
};
`);

console.log(`\n\nDone — ${uploaded} uploaded, ${skipped} already published${missing ? `, ${missing} missing` : ''}.`);
console.log('Wrote lib/extras-products.generated.js');
